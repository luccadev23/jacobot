#!/usr/bin/env python3
"""Generates Sources/JacoDesignSystem/Generated/Tokens.swift from design/tokens.json.

tokens.json is exported from design/jaco.pen and is the single source of colors,
spacing and radii. For other platforms (Windows, Linux, Android), write a
sibling generator that reads the same JSON.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
tokens = json.loads((ROOT / "design" / "tokens.json").read_text())


def camel(name: str) -> str:
    parts = name.split("-")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def resolve(value: str) -> str:
    """Resolves '$ash-900' to the primitive's hex."""
    if value.startswith("$"):
        return resolve(tokens[value[1:]]["v"])
    return value


def rgba(hex_value: str) -> str:
    h = hex_value.lstrip("#").upper()
    if len(h) == 6:
        h += "FF"
    return f"0x{h}"


primitives, semantic, numbers = [], [], []
for name, tok in tokens.items():
    if tok["t"] == "color":
        if "v" in tok and not name.startswith(("bg-", "text-", "border-")):
            if re.match(r"^(ash|ember|green|amber|red|blue|teal|violet|rose|lime)-\d+$|^white$", name):
                primitives.append((name, rgba(resolve(tok["v"]))))
                continue
        if "l" in tok:
            semantic.append((name, rgba(resolve(tok["l"])), rgba(resolve(tok["d"])), tok["l"], tok["d"]))
    elif tok["t"] == "number":
        numbers.append((name, tok["v"]))

out = ["// GENERATED by scripts/generate_tokens.py from design/tokens.json. Do not edit by hand.",
       "import SwiftUI", ""]

out += ["/// Primitive colors (no meaning). Components must not use them directly.",
        "public enum JacoPalette {"]
for name, value in primitives:
    out.append(f"    public static let {camel(name)} = Color(rgba: {value})")
out += ["}", ""]

out += ["/// Semantic colors, switching automatically between light and dark.",
        "public enum JacoColor {"]
for name, l, d, lref, dref in semantic:
    out.append(f"    /// light {lref} · dark {dref}")
    out.append(f"    public static let {camel(name)} = Color.jacoDynamic(light: {l}, dark: {d})")
out += ["}", ""]

space = [(n, v) for n, v in numbers if n.startswith("space-")]
radius = [(n, v) for n, v in numbers if n.startswith("radius-")]
control = [(n, v) for n, v in numbers if n.startswith("control-")]
inset = [(n, v) for n, v in numbers if n.startswith("inset-")]

out += ["/// Spacing scale (base 4).", "public enum JacoSpace {"]
for n, v in space:
    out.append(f"    public static let {camel(n)}: CGFloat = {v}")
out += ["}", "", "public enum JacoRadius {"]
for n, v in radius:
    out.append(f"    public static let {camel(n.replace('radius-', ''))}: CGFloat = {v}")
out += ["}", "", "public enum JacoControl {"]
for n, v in control:
    out.append(f"    public static let {camel(n.replace('control-', ''))}: CGFloat = {v}")
out += ["}", "", "/// Standard side margins. Every screen uses only these: sidebar, desktop panes and mobile.", "public enum JacoInset {"]
for n, v in inset:
    out.append(f"    public static let {camel(n.replace('inset-', ''))}: CGFloat = {v}")
out += ["}", ""]

dest = ROOT / "Sources" / "JacoDesignSystem" / "Generated"
dest.mkdir(parents=True, exist_ok=True)
(dest / "Tokens.swift").write_text("\n".join(out))
print(f"ok: {len(primitives)} primitives, {len(semantic)} semantic, {len(numbers)} numbers")
